class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to calculate total page count and draw running header/footer rules.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 7)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running Top Header
        self.drawString(36, 762, "MEDISCRIPT™ REGULATORY COMPLIANCE VERIFICATION RECORD — CONFIDENTIAL")
        self.setStrokeColor(colors.HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(36, 756, 576, 756)

        # Running Bottom Footer
        self.line(36, 40, 576, 40)
        self.setFont("Helvetica", 7.5)
        self.drawString(36, 28, "Generated by MediScript Engine • Assistive Regulatory Verification Prototype")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(576, 28, page_str)
        self.restoreState()


class ReportService:
    @staticmethod
    async def get_report_preview(db: AsyncSession, review_id: str) -> ReportPreviewResponse:
        """
        Retrieves review metadata, document SHA-256 hashes, and finding stats for preview.
        """
        r_res = await db.execute(
            select(Review).where(Review.id == review_id)
        )
        review = r_res.scalar_one_or_none()
        if not review:
            raise ValueError(f"Review {review_id} not found")

        # Project
        p_res = await db.execute(select(Project).where(Project.id == review.project_id))
        project = p_res.scalar_one_or_none()
        project_name = project.name if project else "Default Project"

        # Checklist Version
        v_res = await db.execute(
            select(ChecklistVersion)
            .where(ChecklistVersion.id == review.checklist_version_id)
            .options(selectinload(ChecklistVersion.checklist), selectinload(ChecklistVersion.rules))
        )
        version = v_res.scalar_one_or_none()
        checklist_name = version.checklist.name if version and version.checklist else "Standard Checklist"
        checklist_ver = version.version if version else "v1.0"
        total_rules = len([r for r in version.rules if r.enabled]) if version and version.rules else 0

        # Documents
        baseline_info: Optional[DocumentHashInfo] = None
        if review.baseline_document_id:
            b_res = await db.execute(select(Document).where(Document.id == review.baseline_document_id))
            b_doc = b_res.scalar_one_or_none()
            if b_doc:
                baseline_info = DocumentHashInfo(
                    filename=b_doc.original_filename or b_doc.filename,
                    file_size_bytes=b_doc.file_size_bytes or 0,
                    sha256=b_doc.sha256 or "N/A",
                    page_count=b_doc.page_count or 1,
                    role="baseline",
                )

        revised_info: Optional[DocumentHashInfo] = None
        if review.revised_document_id:
            rev_res = await db.execute(select(Document).where(Document.id == review.revised_document_id))
            rev_doc = rev_res.scalar_one_or_none()
            if rev_doc:
                revised_info = DocumentHashInfo(
                    filename=rev_doc.original_filename or rev_doc.filename,
                    file_size_bytes=rev_doc.file_size_bytes or 0,
                    sha256=rev_doc.sha256 or "N/A",
                    page_count=rev_doc.page_count or 1,
                    role="revised",
                )

        # Findings
        f_res = await db.execute(select(Finding).where(Finding.review_id == review_id))
        findings = f_res.scalars().all()
        crit_count = sum(1 for f in findings if f.severity == "Critical")
        maj_count = sum(1 for f in findings if f.severity == "Major")
        min_count = sum(1 for f in findings if f.severity == "Minor")
        triaged_count = sum(1 for f in findings if f.status in {FindingStatus.ACCEPTED, FindingStatus.RESOLVED})
        rules_failed = len({f.rule_key for f in findings})
        rules_passed = max(0, total_rules - rules_failed)

        return ReportPreviewResponse(
            review_id=review.id,
            review_name=review.name,
            project_name=project_name,
            status=review.status,
            checklist_name=checklist_name,
            checklist_version=checklist_ver,
            evaluated_at=review.updated_at,
            total_rules_evaluated=total_rules,
            rules_passed=rules_passed,
            rules_failed=rules_failed,
            critical_count=crit_count,
            major_count=maj_count,
            minor_count=min_count,
            triaged_count=triaged_count,
            baseline_doc=baseline_info,
            revised_doc=revised_info,
            disclaimer=REGULATORY_DISCLAIMER,
        )

