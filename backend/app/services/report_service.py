    @staticmethod
    async def generate_json_package(db: AsyncSession, review_id: str) -> Dict[str, Any]:
        """
        Builds a canonical, machine-readable JSON review package (REPT-04).
        """
        r_res = await db.execute(
            select(Review).where(Review.id == review_id)
        )
        review = r_res.scalar_one_or_none()
        if not review:
            raise ValueError(f"Review {review_id} not found")

        # Project
        p_res = await db.execute(select(Project).where(Project.id == review.project_id))
        project = p_res.scalar_one_or_none()

        # Checklist Version
        v_res = await db.execute(
            select(ChecklistVersion)
            .where(ChecklistVersion.id == review.checklist_version_id)
            .options(selectinload(ChecklistVersion.checklist), selectinload(ChecklistVersion.rules))
        )
        version = v_res.scalar_one_or_none()

        # Documents
        baseline_doc: Optional[Document] = None
        if review.baseline_document_id:
            b_res = await db.execute(select(Document).where(Document.id == review.baseline_document_id))
            baseline_doc = b_res.scalar_one_or_none()

        revised_doc: Optional[Document] = None
        if review.revised_document_id:
            rev_res = await db.execute(select(Document).where(Document.id == review.revised_document_id))
            revised_doc = rev_res.scalar_one_or_none()

        # Extracted Entities
        fields_res = await db.execute(
            select(ExtractedField).where(
                ExtractedField.document_id.in_([
                    doc_id for doc_id in [review.baseline_document_id, review.revised_document_id] if doc_id
                ])
            )
        )
        all_fields = fields_res.scalars().all()
        baseline_fields = [f for f in all_fields if f.document_id == review.baseline_document_id]
        revised_fields = [f for f in all_fields if f.document_id == review.revised_document_id]

        # Diff items
        diff_res = await db.execute(
            select(DiffItem).where(DiffItem.review_id == review_id)
        )
        diff_items = diff_res.scalars().all()

        # Findings and Decisions
        f_res = await db.execute(
            select(Finding)
            .where(Finding.review_id == review_id)
            .options(selectinload(Finding.decisions))
        )
        findings = f_res.scalars().all()

        # Activity log
        act_res = await db.execute(
            select(ActivityEvent)
            .where(ActivityEvent.review_id == review_id)
            .order_by(ActivityEvent.created_at.asc())
        )
        activities = act_res.scalars().all()

        now_iso = datetime.now(timezone.utc).isoformat()

        package: Dict[str, Any] = {
            "schema_version": "1.0.0",
            "export_timestamp": now_iso,
            "system": "MediScript Verification Engine",
            "disclaimer": REGULATORY_DISCLAIMER,
            "project": {
                "id": project.id if project else None,
                "name": project.name if project else None,
                "created_at": project.created_at.isoformat() if project and project.created_at else None,
            },
            "review": {
                "id": review.id,
                "name": review.name,
                "status": review.status,
                "checklist_version_id": review.checklist_version_id,
                "created_at": review.created_at.isoformat() if review.created_at else None,
                "updated_at": review.updated_at.isoformat() if review.updated_at else None,
            },
            "checklist": {
                "id": version.checklist.id if version and version.checklist else None,
                "name": version.checklist.name if version and version.checklist else None,
                "jurisdiction": version.checklist.jurisdiction if version and version.checklist else None,
                "version": version.version if version else None,
                "rules": [
                    {
                        "rule_key": r.rule_key,
                        "field_key": r.field_key,
                        "description": r.description,
                        "severity": r.severity,
                        "rule_type": r.rule_type,
                        "expected_value": r.expected_value,
                        "enabled": r.enabled,
                    }
                    for r in (version.rules if version and version.rules else [])
                ],
            },
            "documents": {
                "baseline": {
                    "id": baseline_doc.id,
                    "filename": baseline_doc.original_filename or baseline_doc.filename,
                    "file_size_bytes": baseline_doc.file_size_bytes,
                    "sha256": baseline_doc.sha256,
                    "page_count": baseline_doc.page_count,
                }
                if baseline_doc
                else None,
                "revised": {
                    "id": revised_doc.id,
                    "filename": revised_doc.original_filename or revised_doc.filename,
                    "file_size_bytes": revised_doc.file_size_bytes,
                    "sha256": revised_doc.sha256,
                    "page_count": revised_doc.page_count,
                }
                if revised_doc
                else None,
            },
            "extracted_entities": {
                "baseline": [
                    {
                        "field_key": ef.field_key,
                        "field_label": ef.field_label,
                        "category": ef.category,
                        "value": ef.value,
                        "normalized_value": ef.normalized_value,
                        "confidence_state": ef.confidence_state,
                        "evidence_page": ef.evidence_page,
                        "coordinates": {
                            "norm_x0": ef.norm_x0,
                            "norm_y0": ef.norm_y0,
                            "norm_x1": ef.norm_x1,
                            "norm_y1": ef.norm_y1,
                        },
                    }
                    for ef in baseline_fields
                ],
                "revised": [
                    {
                        "field_key": ef.field_key,
                        "field_label": ef.field_label,
                        "category": ef.category,
                        "value": ef.value,
                        "normalized_value": ef.normalized_value,
                        "confidence_state": ef.confidence_state,
                        "evidence_page": ef.evidence_page,
                        "coordinates": {
                            "norm_x0": ef.norm_x0,
                            "norm_y0": ef.norm_y0,
                            "norm_x1": ef.norm_x1,
                            "norm_y1": ef.norm_y1,
                        },
                    }
                    for ef in revised_fields
                ],
            },
            "revision_diff": {
                "total_changes": len(diff_items),
                "items": [
                    {
                        "id": d.id,
                        "change_type": d.change_type,
                        "category": d.category,
                        "significance": d.significance,
                        "baseline_text": d.baseline_text,
                        "revised_text": d.revised_text,
                        "baseline_page": d.baseline_page,
                        "revised_page": d.revised_page,
                        "is_promoted": d.is_promoted,
                    }
                    for d in diff_items
                ],
            },
            "compliance_findings": [
                {
                    "id": f.id,
                    "rule_key": f.rule_key,
                    "category": f.category,
                    "severity": f.severity,
                    "status": f.status,
                    "explanation": f.explanation,
                    "expected_value": f.expected_value,
                    "observed_value": f.observed_value,
                    "document_role": f.document_role,
                    "page_number": f.page_number,
                    "coordinates": {
                        "norm_x0": f.norm_x0,
                        "norm_y0": f.norm_y0,
                        "norm_x1": f.norm_x1,
                        "norm_y1": f.norm_y1,
                    },
                    "decisions": [
                        {
                            "id": dec.id,
                            "prior_status": dec.prior_status,
                            "new_status": dec.new_status,
                            "actor": dec.actor,
                            "actor_role": dec.actor_role,
                            "note": dec.note,
                            "created_at": dec.created_at.isoformat(),
                        }
                        for dec in (f.decisions or [])
                    ],
                }
                for f in findings
            ],
            "activity_trail": [
                {
                    "id": a.id,
                    "event_type": a.event_type,
                    "actor": a.actor,
                    "details": a.details,
                    "created_at": a.created_at.isoformat(),
                }
                for a in activities
            ],
        }

        return package
